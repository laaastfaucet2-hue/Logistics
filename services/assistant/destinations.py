# أوزان إضافية للأوامر: فعل أمر + وجهة = تنقل فوري
OPEN_VERBS = ("افتح", "افتحلي", "روح", "روحلي", "اذهب", "ادخل", "وديني", "خدني",
              "هات", "اروح", "أروح", "اظهر", "وريني", "عايز", "عاوز", "عرض",
              "انتقل", "نقلني", "شوف", "اعرض")

_BY_KEY = {dest[0]: dest for dest in DESTINATIONS}


def by_key(key):
    return _BY_KEY.get(key)


def resolve(question):
    """أفضل وجهة مطابقة للسؤال (أطول كلمة مفتاحية تِغلب) أو None.

    عند التعادل يُرجَّح الأكثر تخصيصًا: مطابقة عبارة مركّبة (`tameedat.momoda`)
    تتقدم على مطابقة كلمة عامة (`tameedat.day`) حتى لو ظهرت الاثنتان.
    """
    best, best_score = None, 0.0
    for dest in DESTINATIONS:
        score = 0.0
        for keyword in dest[4]:
            key = normalize(keyword)
            if not key:
                continue
            if key in question:
                score += len(key) + 2 + (4 if " " in key else 0)
            elif phrase_in(question, key, threshold=0.86):
                score += (len(key) + 2) * 0.8
        if score > best_score:
            best, best_score = dest, score
    return best if best_score >= 5 else None


def wants_navigation(question):
    """هل في السؤال فعل أمر يعني «وديني للتاب»."""
    return any(phrase_in(question, verb) for verb in OPEN_VERBS)


def label(key):
    dest = _BY_KEY.get(key)
    return dest[1] if dest else key
